CREATE TABLE IF NOT EXISTS agendas (
 id SERIAL PRIMARY KEY,nomor_surat VARCHAR(100) NOT NULL,perihal VARCHAR(255) NOT NULL,
 periode VARCHAR(100) NOT NULL,zoom_url VARCHAR(500) NOT NULL DEFAULT '',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS attendances (
 id SERIAL PRIMARY KEY,agenda_id INTEGER NOT NULL REFERENCES agendas(id) ON DELETE CASCADE,
 nama VARCHAR(150) NOT NULL,instansi VARCHAR(150) NOT NULL DEFAULT '',
 status VARCHAR(20) NOT NULL CHECK(status IN ('Hadir','Izin','Tidak Hadir')),catatan VARCHAR(500) NOT NULL DEFAULT '',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS documents (
 id SERIAL PRIMARY KEY,agenda_id INTEGER NOT NULL REFERENCES agendas(id) ON DELETE CASCADE,
 nama_pengirim VARCHAR(150) NOT NULL,judul_dokumen VARCHAR(200) NOT NULL,
 nama_file VARCHAR(255) NOT NULL,mime_type VARCHAR(150) NOT NULL,ukuran INTEGER NOT NULL,
 content BYTEA NOT NULL,catatan VARCHAR(500) NOT NULL DEFAULT '',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS attendances_agenda_idx ON attendances(agenda_id);
CREATE INDEX IF NOT EXISTS documents_agenda_idx ON documents(agenda_id);
